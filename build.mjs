// Builds ../1-UPLOAD-TO-WEBSITE/hr/index.html from the source code.  Run:  npm install  then  npm run build
import * as esbuild from 'esbuild';
import fs from 'fs';
await esbuild.build({ entryPoints: ['entry.jsx'], bundle: true, minify: true, format: 'iife', outfile: 'dist/app.js',
  loader: { '.png': 'dataurl', '.js': 'jsx' }, jsx: 'automatic', legalComments: 'none',
  define: { 'process.env.REACT_APP_SUPABASE_URL': 'undefined', 'process.env.REACT_APP_SUPABASE_ANON_KEY': 'undefined', 'process.env.NODE_ENV': '"production"', 'import.meta.env': 'undefined' } });
const js = fs.readFileSync('dist/app.js', 'utf8').replace(/<\/script/gi, '<\\/script');
const css = fs.readFileSync('dist/app.css', 'utf8').replace(/@import\s*(?:url\()?["']https:\/\/fonts[^"']*["']\)?;?/g, '');
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="robots" content="noindex, nofollow">
<title>H4ZP HR</title>
<!--
  H4ZP HR — Hands 4 Zero Poverty Trust
  Do not edit this file. Your Supabase keys go in config.js (same folder).
  To update H4ZP HR later, replace only this index.html — config.js keeps your keys.
-->
<script src="config.js"></script>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Figtree:wght@400;500;600;700;800&display=swap" rel="stylesheet">
<style>body{margin:0;background:#f4f7f6}
${css}</style>
</head>
<body>
<div id="root"></div>
<script>
${js}
</script>
</body>
</html>
`;
fs.mkdirSync('../1-UPLOAD-TO-WEBSITE/hr', { recursive: true });
fs.writeFileSync('../1-UPLOAD-TO-WEBSITE/hr/index.html', html);
console.log('Built 1-UPLOAD-TO-WEBSITE/hr/index.html —', Math.round(html.length / 1024), 'KB');
